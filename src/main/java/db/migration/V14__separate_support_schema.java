package db.migration;

import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

import java.sql.Connection;
import java.sql.Statement;

public class V14__separate_support_schema extends BaseJavaMigration {
    private static final String[] TABLES = {
            "hitos_obra", "obras_ingenieros", "suscripciones_newsletter", "auditoria_eventos"
    };

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        String database = connection.getMetaData().getDatabaseProductName();
        if (!database.equals("PostgreSQL") && !database.equals("H2")) {
            throw new IllegalStateException("Motor no compatible con el traslado de esquemas.");
        }
        try (Statement statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA IF NOT EXISTS apoyo");
            if (database.equals("PostgreSQL")) {
                for (String table : TABLES) {
                    statement.execute("ALTER TABLE public." + table + " SET SCHEMA apoyo");
                }
            } else {
                migrateH2(statement);
            }
        }
    }

    // H2 does not support PostgreSQL's ALTER TABLE ... SET SCHEMA.
    private void migrateH2(Statement statement) throws Exception {
        statement.execute("""
                CREATE TABLE apoyo.hitos_obra (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(255) NOT NULL, descripcion VARCHAR(1000), fecha_objetivo DATE,
                    completado BOOLEAN NOT NULL DEFAULT FALSE,
                    obra_id BIGINT NOT NULL REFERENCES public.obras(id))
                """);
        statement.execute("""
                CREATE TABLE apoyo.obras_ingenieros (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    obra_id BIGINT NOT NULL REFERENCES public.obras(id),
                    usuario_id BIGINT NOT NULL REFERENCES public.administradores_autorizados(id),
                    asignado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                    asignado_por VARCHAR(255) NOT NULL,
                    CONSTRAINT uk_obra_ingeniero UNIQUE (obra_id, usuario_id))
                """);
        statement.execute("""
                CREATE TABLE apoyo.suscripciones_newsletter (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    correo VARCHAR(254) NOT NULL UNIQUE, acepta_politica BOOLEAN NOT NULL,
                    version_politica VARCHAR(50) NOT NULL,
                    fecha_consentimiento TIMESTAMP WITHOUT TIME ZONE NOT NULL)
                """);
        statement.execute("""
                CREATE TABLE apoyo.auditoria_eventos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actor_uid VARCHAR(255) NOT NULL, accion VARCHAR(100) NOT NULL, obra_id BIGINT,
                    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL, ip VARCHAR(64))
                """);
        for (String table : TABLES) {
            statement.executeUpdate("INSERT INTO apoyo." + table + " SELECT * FROM public." + table);
            long nextId;
            try (var rows = statement.executeQuery("SELECT COALESCE(MAX(id), 0) + 1 FROM apoyo." + table)) {
                rows.next();
                nextId = rows.getLong(1);
            }
            statement.execute("ALTER TABLE apoyo." + table + " ALTER COLUMN id RESTART WITH " + nextId);
            statement.execute("DROP TABLE public." + table);
        }
    }
}
