-- Esquema de referencia de la aplicacion.
-- La migracion ejecutable para bases nuevas es db/migration/V1__initial_schema.sql.

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255),
    nombre VARCHAR(255),
    rol VARCHAR(32) NOT NULL DEFAULT 'USUARIO',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE administradores_autorizados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    rol VARCHAR(32) NOT NULL DEFAULT 'INGENIERO',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por VARCHAR(255),
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE servicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    precio_base_m2 NUMERIC(38, 2) NOT NULL,
    categoria VARCHAR(255) NOT NULL,
    activo BOOLEAN
);

CREATE TABLE labores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE riesgos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(1000) NOT NULL,
    nivel_severidad VARCHAR(255) NOT NULL,
    labor_id BIGINT NOT NULL REFERENCES labores(id)
);

CREATE TABLE epps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(255),
    labor_id BIGINT NOT NULL REFERENCES labores(id)
);

CREATE TABLE politicas_ambientales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL
);

CREATE TABLE obras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_obra VARCHAR(255) NOT NULL,
    codigo_seguimiento VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    porcentaje_avance INTEGER NOT NULL,
    cliente_id BIGINT NOT NULL
);

CREATE TABLE foto_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(255) NOT NULL,
    fecha DATE NOT NULL,
    obra_id BIGINT NOT NULL REFERENCES obras(id)
);

CREATE TABLE solicitudes_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    empresa VARCHAR(255),
    correo VARCHAR(255) NOT NULL,
    telefono VARCHAR(255),
    tipo_servicio VARCHAR(255) NOT NULL,
    nivel_riesgo_sst VARCHAR(255) NOT NULL,
    mensaje VARCHAR(2000) NOT NULL,
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE logs_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL,
    pregunta VARCHAR(2000) NOT NULL,
    respuesta VARCHAR(4000) NOT NULL,
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
