CREATE TABLE hitos_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(1000),
    fecha_objetivo DATE,
    completado BOOLEAN NOT NULL DEFAULT FALSE,
    obra_id BIGINT NOT NULL REFERENCES obras(id)
);

CREATE TABLE obras_ingenieros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id BIGINT NOT NULL REFERENCES obras(id),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    asignado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    asignado_por VARCHAR(255) NOT NULL,
    CONSTRAINT uk_obra_ingeniero UNIQUE (obra_id, usuario_id)
);

CREATE TABLE auditoria_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_uid VARCHAR(255) NOT NULL,
    accion VARCHAR(100) NOT NULL,
    obra_id BIGINT,
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ip VARCHAR(64)
);
