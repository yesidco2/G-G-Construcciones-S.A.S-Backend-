CREATE TABLE apoyo.documentos_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id BIGINT NOT NULL REFERENCES apoyo.obras_ingenieros(id) ON DELETE CASCADE,
    nombre VARCHAR(200) NOT NULL,
    huella VARCHAR(64) NOT NULL,
    contenido BYTEA NOT NULL,
    UNIQUE (obra_id, huella)
);

CREATE TABLE apoyo.fotos_perfil (
    usuario_id BIGINT PRIMARY KEY REFERENCES public.administradores_autorizados(id) ON DELETE CASCADE,
    contenido BYTEA NOT NULL
);
