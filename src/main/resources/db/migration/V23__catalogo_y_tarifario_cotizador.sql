-- Catálogo comercial leído por el backend. La unidad identifica la base de cálculo en COP.
CREATE TABLE apoyo.cotizador_servicios (
    id VARCHAR(80) PRIMARY KEY,
    categoria VARCHAR(80) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    unidad VARCHAR(40) NOT NULL DEFAULT 'servicio completo' CHECK (TRIM(unidad) <> ''),
    orden INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- Una tarifa se publica para un servicio, unidad, periodo y municipio determinados.
-- '*' significa cobertura nacional aprobada expresamente para ese importe.
CREATE TABLE apoyo.cotizador_tarifas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio_id VARCHAR(80) NOT NULL REFERENCES apoyo.cotizador_servicios(id),
    unidad VARCHAR(40) NOT NULL CHECK (TRIM(unidad) <> ''),
    tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('APROBADA', 'REFERENCIA')),
    precio_unitario NUMERIC(14,2) NOT NULL CHECK (precio_unitario > 0),
    fuente VARCHAR(500) NOT NULL CHECK (TRIM(fuente) <> ''),
    fecha_fuente DATE NOT NULL,
    ubicacion VARCHAR(120) NOT NULL CHECK (TRIM(ubicacion) <> ''),
    alcance VARCHAR(1000) NOT NULL CHECK (TRIM(alcance) <> ''),
    vigente_desde DATE NOT NULL,
    vigente_hasta DATE,
    activa BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (fecha_fuente <= vigente_desde),
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
    CHECK (tipo <> 'REFERENCIA' OR vigente_hasta IS NOT NULL),
    UNIQUE (servicio_id, unidad, tipo, ubicacion, vigente_desde)
);

-- Cada fila es una política comercial completa para una ubicación y un periodo.
-- NULL indica que ese ajuste o condición no se ha definido.
CREATE TABLE apoyo.cotizador_condiciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion VARCHAR(120) NOT NULL CHECK (TRIM(ubicacion) <> ''),
    vigente_desde DATE NOT NULL,
    vigente_hasta DATE,
    dias_vigencia INTEGER CHECK (dias_vigencia > 0 AND dias_vigencia <= 3650),
    condiciones VARCHAR(3000),
    alcance VARCHAR(2000),
    desplazamiento NUMERIC(14,2) CHECK (desplazamiento >= 0),
    descuento_porcentaje NUMERIC(7,4) CHECK (descuento_porcentaje BETWEEN 0 AND 100),
    impuesto_porcentaje NUMERIC(7,4) CHECK (impuesto_porcentaje BETWEEN 0 AND 100),
    activa BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
    UNIQUE (ubicacion, vigente_desde)
);

